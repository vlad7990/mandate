/**
 * THE RESTORE REHEARSAL — requirements 11, 12 and 13.
 *
 * A backup is a hypothesis until it has been restored. This harness is
 * the experiment: it builds an isolated throwaway database, seeds two
 * tenants with synthetic candidate records and synthetic CV files, backs
 * them up, destroys BOTH the database and the source files, restores
 * from the backup, and then checks the three things that actually matter
 * after a restore —
 *
 *   * every object is byte-identical (integrity);
 *   * every `cv_url` and `audio_path` still resolves (path reconstruction);
 *   * tenant isolation still holds (RLS survived the restore).
 *
 * It measures the elapsed restore time, which is the only honest source
 * of an RTO figure.
 *
 * ## Isolated, synthetic, local
 *
 * Nothing here touches production. The database is a throwaway created
 * and dropped by this file, the files are generated bytes, and the
 * destination is a temp directory. No production backup is taken and no
 * production restore is performed — both require approval.
 *
 * Run with: `npm run rehearse`
 */

/**
 * ISOLATION: a throwaway database on the local cluster, created in
 * beforeAll and dropped in afterAll. Nothing production is touched.
 *
 * ⚠️ VERSION GAP, disclosed rather than papered over: the local cluster
 * is PostgreSQL 14.19 and production is 17.6. Everything this rehearsal
 * exercises — RLS, plain SQL functions, advisory locks, pg_dump custom
 * format — behaves identically across those versions, so the restore
 * LOGIC is genuinely proven. What is NOT proven is 17.6-specific
 * behaviour, so the production rehearsal (activation step 11) remains
 * required and the RTO below is not a production figure.
 *
 * The original version of this harness used a `postgres:17` container to
 * close that gap. It is retained in git history and should be preferred
 * when the Docker daemon is responsive; it was unusable on 2026-10-07.
 */
const DB = `mandate_rehearsal_${process.pid}`;
const KEY = generateKeyBase64();

let workDir: string;
let sourceDir: string;
let destDir: string;
let restoreDir: string;
let dumpFile: string;
let destination: Destination;

/** Run SQL against the throwaway database. */
function sql(statement: string, opts: { role?: string; claims?: string; db?: string } = {}): string {
  let body = statement;
  if (opts.role || opts.claims) {
    const pre: string[] = [];
    if (opts.claims) pre.push(`SET request.jwt.claims = '${opts.claims}';`);
    if (opts.role) pre.push(`SET ROLE ${opts.role};`);
    body = `${pre.join("\n")}\n${statement}`;
  }
  return execFileSync(
    "psql",
    ["-h", "127.0.0.1", "-p", "5432", "-d", opts.db ?? DB, "-t", "-A", "-F", "|", "-v", "ON_ERROR_STOP=1", "-c", body],
    { encoding: "utf8" }
  ).trim();
}

function pg(bin: string, args: string[], allowFail = false): string {
  try {
    return execFileSync(bin, args, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
  } catch (err) {
    if (allowFail) return "";
    throw err;
  }
}

/**
 * A Supabase-shaped client backed by the throwaway Postgres and a local
 * directory standing in for Storage. The backup module under test is
 * the real one — only the edges are substituted.
 */
function makeHarnessClient(args: { sourceDir: string }): SupabaseClient {
  const listDir = async (bucket: string) => {
    const base = path.join(args.sourceDir, bucket);
    const out: Array<{ name: string; size: number; updatedAt: string }> = [];
    async function walk(dir: string, prefix: string) {
      let items;
      try {
        items = await fs.readdir(dir, { withFileTypes: true });
      } catch {
        return;
      }
      for (const it of items) {
        const full = path.join(dir, it.name);
        const key = prefix ? `${prefix}/${it.name}` : it.name;
        if (it.isDirectory()) await walk(full, key);
        else {
          const st = await fs.stat(full);
          out.push({ name: key, size: st.size, updatedAt: st.mtime.toISOString() });
        }
      }
    }
    await walk(base, "");
    return out;
  };

  const rows = (statement: string): Array<Record<string, string>> => {
    const raw = sql(statement);
    if (!raw) return [];
    return raw.split("\n").map((line) => {
      const parts = line.split("|");
      return Object.fromEntries(parts.map((v, i) => [`c${i}`, v]));
    });
  };

  return {
    rpc(fn: string) {
      if (fn === "backup_try_lock") {
        return Promise.resolve({ data: sql("select public.backup_try_lock();") === "t", error: null });
      }
      if (fn === "backup_release_lock") {
        return Promise.resolve({ data: true, error: null });
      }
      if (fn === "backup_storage_policy_snapshot") {
        const r = rows(
          "select policyname, cmd, roles::text from pg_policies where schemaname='public' and tablename='candidates' order by policyname;"
        );
        return Promise.resolve({
          data: r.map((x) => ({ policyname: x.c0, cmd: x.c1, roles: [x.c2] })),
          error: null,
        });
      }
      return Promise.resolve({ data: null, error: { message: "no such function" } });
    },
    from(table: string) {
      const state = { head: false, limited: false };
      const resolve = () => {
        if (table === "network_suppressions") {
          const r = rows("select profile_id from public.network_suppressions where lifted_at is null;");
          return { data: r.map((x) => ({ profile_id: x.c0 })), error: null };
        }
        if (table === "candidates") {
          if (state.head) {
            return { data: null, error: null, count: Number(sql("select count(*) from public.candidates;")) };
          }
          if (state.limited) {
            return { data: [{ updated_at: sql("select max(updated_at) from public.candidates;") }], error: null };
          }
          const r = rows(
            "select id, coalesce(cv_url,''), coalesce(network_profile_id::text,'') from public.candidates where network_profile_id in (select profile_id from public.network_suppressions where lifted_at is null);"
          );
          return {
            data: r.map((x) => ({ id: x.c0, cv_url: x.c1 || null, network_profile_id: x.c2 || null })),
            error: null,
          };
        }
        if (table === "candidate_notes") {
          if (state.head) {
            return {
              data: null,
              error: null,
              count: Number(sql("select count(*) from public.candidate_notes where audio_path is not null;")),
            };
          }
          const r = rows(
            "select candidate_id, audio_path from public.candidate_notes where audio_path is not null and candidate_id in (select id from public.candidates where network_profile_id in (select profile_id from public.network_suppressions where lifted_at is null));"
          );
          return { data: r.map((x) => ({ candidate_id: x.c0, audio_path: x.c1 })), error: null };
        }
        return { data: [], error: null };
      };
      const builder: Record<string, unknown> = {
        select: (_c?: string, o?: { head?: boolean }) => {
          if (o?.head) state.head = true;
          return builder;
        },
        is: () => builder,
        not: () => builder,
        in: () => builder,
        order: () => builder,
        limit: () => {
          state.limited = true;
          return builder;
        },
        then: (ok: (v: unknown) => unknown, bad?: (e: unknown) => unknown) =>
          Promise.resolve(resolve()).then(ok, bad),
      };
      return builder;
    },
    storage: {
      from(bucket: string) {
        return {
          async list(prefix: string) {
            if (prefix !== "") return { data: [], error: null };
            const items = await listDir(bucket);
            return {
              data: items.map((i) => ({
                id: `id-${i.name}`,
                name: i.name,
                updated_at: i.updatedAt,
                metadata: { size: i.size, mimetype: "application/pdf" },
              })),
              error: null,
            };
          },
          async download(key: string) {
            try {
              const body = await fs.readFile(path.join(args.sourceDir, bucket, key));
              return { data: { arrayBuffer: async () => body }, error: null };
            } catch {
              return { data: null, error: { message: "not found" } };
            }
          },
        };
      },
      async listBuckets() {
        return {
          data: [
            { name: "cvs", public: false, file_size_limit: 10485760, allowed_mime_types: ["application/pdf"] },
            { name: "call-audio", public: false, file_size_limit: 52428800, allowed_mime_types: ["audio/mpeg"] },
            { name: "invoice-assets", public: false, file_size_limit: 2097152, allowed_mime_types: ["image/png"] },
          ],
          error: null,
        };
      },
    },
  } as unknown as SupabaseClient;
}

const SCHEMA = `
create extension if not exists pgcrypto;

create table public.organizations (
  id uuid primary key default gen_random_uuid(),
  name text not null
);

create table public.network_profiles (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id),
  display_name text not null
);

create table public.network_suppressions (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id),
  profile_id uuid not null references public.network_profiles(id),
  reason text not null,
  set_at timestamptz not null default now(),
  lifted_at timestamptz
);

create table public.candidates (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id),
  network_profile_id uuid references public.network_profiles(id),
  full_name text not null,
  cv_url text,
  updated_at timestamptz not null default now()
);

create table public.candidate_notes (
  id uuid primary key default gen_random_uuid(),
  candidate_id uuid not null references public.candidates(id),
  audio_path text
);

-- Tenant isolation, the property requirement 13 asks us to re-verify
-- AFTER a restore. Mirrors the shape of production's org scoping:
-- the org comes from the JWT, not from the client.
create or replace function public.current_user_org_id()
returns uuid language sql stable set search_path = '' as $$
  select nullif(
    pg_catalog.current_setting('request.jwt.claims', true)::json->>'org_id',
    ''
  )::uuid;
$$;

alter table public.candidates enable row level security;
create policy candidates_org_read on public.candidates
  for select to authenticated
  using (organization_id = (select public.current_user_org_id()));

grant usage on schema public to authenticated;
grant select on public.candidates to authenticated;

-- The lock wrapper from migration 161, so the real runner's lock path
-- is exercised rather than stubbed.
create or replace function public.backup_try_lock()
returns boolean language sql volatile set search_path = '' as $$
  select pg_catalog.pg_try_advisory_lock(8427301);
$$;
`;

